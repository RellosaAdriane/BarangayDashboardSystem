CREATE TABLE IF NOT EXISTS public.camera_recordings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camera_id bigint NOT NULL REFERENCES public.cameras(id) ON DELETE CASCADE,
  file_name varchar(100) NOT NULL,
  started_at timestamp NOT NULL,
  ended_at timestamp NOT NULL,
  duration_seconds integer NOT NULL,
  file_size_bytes bigint NOT NULL,
  storage_path text,
  archived_at timestamp,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (camera_id, file_name)
);
ALTER TABLE public.camera_recordings ADD COLUMN IF NOT EXISTS storage_path text;
ALTER TABLE public.camera_recordings ADD COLUMN IF NOT EXISTS archived_at timestamp;
ALTER TABLE public.camera_recordings ADD COLUMN IF NOT EXISTS storage_provider text NOT NULL DEFAULT 'supabase';
ALTER TABLE public.camera_recordings ADD COLUMN IF NOT EXISTS device_recording_id text;
CREATE UNIQUE INDEX IF NOT EXISTS camera_recordings_device_id ON public.camera_recordings (camera_id, device_recording_id);
CREATE INDEX IF NOT EXISTS camera_recordings_camera_time ON public.camera_recordings (camera_id, started_at);
ALTER TABLE public.camera_recordings ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.camera_device_tokens (
  camera_id bigint PRIMARY KEY REFERENCES public.cameras(id) ON DELETE CASCADE,
  token_hash text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.camera_device_tokens ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.device_recording_uploads (
  camera_id bigint NOT NULL REFERENCES public.cameras(id) ON DELETE CASCADE,
  recording_id text NOT NULL,
  storage_path text NOT NULL UNIQUE,
  file_name varchar(100) NOT NULL,
  started_at timestamptz NOT NULL,
  ended_at timestamptz NOT NULL,
  file_size_bytes bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (camera_id, recording_id)
);
ALTER TABLE public.device_recording_uploads ENABLE ROW LEVEL SECURITY;
