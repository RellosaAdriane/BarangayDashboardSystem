CREATE TABLE IF NOT EXISTS public.enrolled_faces (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name varchar(120) NOT NULL,
  descriptor double precision[] NOT NULL CHECK (cardinality(descriptor) = 128),
  photo bytea NOT NULL,
  photo_type text NOT NULL CHECK (photo_type IN ('image/jpeg', 'image/png', 'image/webp')),
  enrolled_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
  enrolled_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.enrolled_faces ENABLE ROW LEVEL SECURITY;
