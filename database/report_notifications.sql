CREATE TABLE IF NOT EXISTS public.report_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_id bigint NOT NULL REFERENCES public.camera_alerts(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz,
  UNIQUE (alert_id, user_id)
);
CREATE INDEX IF NOT EXISTS report_notifications_user_idx ON public.report_notifications (user_id, created_at DESC, id DESC);
ALTER TABLE public.report_notifications ENABLE ROW LEVEL SECURITY;
