CREATE TABLE IF NOT EXISTS public.snapshot_notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_id bigint NOT NULL REFERENCES public.camera_alerts(id) ON DELETE CASCADE,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz,
  UNIQUE (alert_id, user_id)
);
CREATE INDEX IF NOT EXISTS snapshot_notifications_user_idx ON public.snapshot_notifications (user_id, created_at DESC, id DESC);
ALTER TABLE public.snapshot_notifications ENABLE ROW LEVEL SECURITY;
INSERT INTO public.snapshot_notifications (alert_id, user_id)
SELECT a.id, u.id FROM public.camera_alerts a CROSS JOIN public.users u
WHERE a.status = 'pending' AND u.role IN ('admin', 'captain')
  AND u.is_active = true AND u.approval_status = 'approved'
ON CONFLICT (alert_id, user_id) DO NOTHING;
