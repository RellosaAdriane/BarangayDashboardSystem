create table if not exists public.users (
  id bigint generated by default as identity primary key,
  full_name varchar(120) not null,
  first_name varchar(60),
  middle_name varchar(60),
  last_name varchar(60),
  gender text check (gender in ('female','male')),
  date_of_birth date,
  username varchar(60) not null unique,
  password_hash varchar(255) not null,
  role text not null default 'tanod' check (role in ('tanod','captain','admin')),
  is_active boolean not null default true,
  approval_status text not null default 'approved'
    check (approval_status in ('pending','approved','declined')),
  requested_role text check (requested_role in ('tanod','captain')),
  reviewed_by bigint,
  reviewed_at timestamp,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title varchar(180) not null,
  body text not null,
  is_published boolean not null default true,
  published_at timestamp,
  created_by bigint,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  user_id bigint,
  action varchar(100) not null,
  entity_type varchar(60) not null,
  entity_id bigint,
  details jsonb,
  ip_address varchar(45),
  created_at timestamptz not null default now()
);

create table if not exists public.cameras (
  id bigint generated by default as identity primary key,
  name varchar(100) not null,
  stream_url varchar(2048) not null,
  location varchar(200),
  is_enabled boolean not null default true,
  last_status text not null default 'unknown'
    check (last_status in ('unknown','online','offline')),
  last_checked_at timestamp,
  is_archived boolean not null default false,
  created_by bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.incidents (
  id bigint generated by default as identity primary key,
  reference_no varchar(24) not null unique,
  type varchar(100) not null,
  note text,
  actions_taken text,
  captured_image bytea,
  captured_mime varchar(64),
  review_result varchar(255),
  status text not null default 'Pending'
    check (status in ('Pending','Resolved','Archived')),
  camera_id bigint,
  reported_by bigint,
  occurred_at timestamp not null default now(),
  archived_at timestamp,
  created_at timestamptz not null default now()
);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title varchar(180) not null,
  details text,
  status text not null default 'Pending'
    check (status in ('Pending','In Progress','Completed','Cancelled')),
  assigned_to bigint,
  assigned_by bigint,
  due_at timestamp,
  duty_starts_at timestamp,
  duty_ends_at timestamp,
  completed_at timestamp,
  proof_description text,
  proof_image varchar(255),
  proof_submitted_at timestamp,
  proof_status text check (proof_status in ('Pending','Approved','Rejected')),
  proof_reviewed_by bigint,
  proof_reviewed_at timestamp,
  created_at timestamptz not null default now()
);

