-- Runtime tables used by the dashboard but absent from the imported schema.
-- Run this in the Supabase SQL Editor after importing barangaywatch_supabase_schema.sql.

create table if not exists public.calendar_events (
  id bigint generated by default as identity primary key,
  title varchar(180) not null,
  details text,
  location varchar(200),
  starts_at timestamp not null,
  ends_at timestamp not null,
  created_by bigint references public.users(id) on delete set null,
  updated_by bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_calendar_events_dates on public.calendar_events (starts_at, ends_at);
create index if not exists idx_calendar_events_creator on public.calendar_events (created_by);
alter table public.calendar_events enable row level security;

create table if not exists public.camera_recordings (
  id bigint generated by default as identity primary key,
  camera_id bigint not null references public.cameras(id) on delete cascade,
  file_name varchar(100) not null,
  started_at timestamp not null,
  ended_at timestamp not null,
  duration_seconds integer not null default 0,
  file_size_bytes bigint not null default 0,
  archived_at timestamp,
  created_at timestamptz not null default now(),
  constraint uq_recordings_camera_file unique (camera_id, file_name)
);
create index if not exists idx_recordings_camera_time on public.camera_recordings (camera_id, started_at);
create index if not exists idx_recordings_time on public.camera_recordings (started_at, ended_at);
create index if not exists idx_recordings_archive on public.camera_recordings (archived_at);
alter table public.camera_recordings enable row level security;

-- Private evidence files live in Supabase Storage and are served by the
-- authenticated Express API.
alter table public.camera_recordings add column if not exists storage_path text;
alter table public.incidents
  add column if not exists snapshot_path text;


-- Keep server-side session data outside Supabase's exposed public schema.
create schema if not exists private;

create or replace function public.set_calendar_event_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
drop trigger if exists calendar_events_set_updated_at on public.calendar_events;
create trigger calendar_events_set_updated_at before update on public.calendar_events
for each row execute function public.set_calendar_event_updated_at();
